SELECT CONVERT(nvarchar(50), CONVERT(varchar(12), f.ORIGIN_AIRPORT_ID) + N'_' + CONVERT(varchar(12), f.DEST_AIRPORT_ID)) AS ROUTE_KEY,
       CONVERT(nvarchar(105), o.AIRPORT_CODE + N' - ' + d.AIRPORT_CODE) AS ROUTE_NAME,
       o.AIRPORT_CODE AS ORIGIN_CODE, d.AIRPORT_CODE AS DEST_CODE,
       MIN(f.DISTANCE) AS DISTANCE_MILES,
       CONVERT(nvarchar(20), MIN(f.DISTANCE)) AS DISTANCE_CAPTION
FROM dbo.FACT_FLIGHT f
JOIN dbo.DIM_AIRPORT o ON o.AIRPORT_ID = f.ORIGIN_AIRPORT_ID
JOIN dbo.DIM_AIRPORT d ON d.AIRPORT_ID = f.DEST_AIRPORT_ID
GROUP BY f.ORIGIN_AIRPORT_ID, f.DEST_AIRPORT_ID, o.AIRPORT_CODE, d.AIRPORT_CODE
