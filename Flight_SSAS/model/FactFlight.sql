SELECT f.*,
       CONVERT(nvarchar(50), CONVERT(varchar(12), ORIGIN_AIRPORT_ID) + N'_' + CONVERT(varchar(12), DEST_AIRPORT_ID)) AS ROUTE_KEY,
       CAST(1 AS bigint) AS TOTAL_FLIGHTS,
       CAST(CASE WHEN CANCELLED = 0 THEN 1 ELSE 0 END AS bigint) AS OPERATED_FLIGHTS,
       CAST(CANCELLED AS bigint) AS CANCELLED_FLIGHTS,
       CAST(CASE WHEN CANCELLED = 0 AND DEP_DELAY IS NOT NULL THEN 1 ELSE 0 END AS bigint) AS DEPARTURE_OBSERVATIONS,
       CAST(CASE WHEN CANCELLED = 0 AND ARR_DELAY IS NOT NULL THEN 1 ELSE 0 END AS bigint) AS ARRIVAL_OBSERVATIONS,
       CAST(CASE WHEN CANCELLED = 0 AND DEP_DELAY >= 15 THEN 1 ELSE 0 END AS bigint) AS DELAYED_DEPARTURES,
       CASE WHEN CANCELLED = 0 AND DEP_DELAY > 0 THEN DEP_DELAY ELSE 0.0 END AS DEPARTURE_LATE_MINUTES,
       CASE WHEN CANCELLED = 0 AND ARR_DELAY > 0 THEN ARR_DELAY ELSE 0.0 END AS ARRIVAL_LATE_MINUTES,
       CASE WHEN CANCELLED = 0 THEN DEP_DELAY ELSE NULL END AS DEPARTURE_DELAY_VALUE,
       CASE WHEN CANCELLED = 0 THEN ARR_DELAY ELSE NULL END AS ARRIVAL_DELAY_VALUE
FROM dbo.FACT_FLIGHT f
