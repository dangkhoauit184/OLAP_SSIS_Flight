SELECT DATE_ID, FL_DATE, YEAR_NUM, QUARTER_NUM, MONTH_NUM, DAY_NUM,
       YEAR_NUM * 10 + QUARTER_NUM AS QUARTER_KEY,
       YEAR_NUM * 100 + MONTH_NUM AS MONTH_KEY,
       CONVERT(nvarchar(10), FL_DATE, 23) AS DATE_CAPTION,
       CONVERT(nvarchar(4), YEAR_NUM) AS YEAR_CAPTION,
       RIGHT(N'0' + CONVERT(nvarchar(2), MONTH_NUM), 2) AS MONTH_NUMBER_CAPTION,
       N'Q' + CONVERT(nvarchar(1), QUARTER_NUM) + N'/' + CONVERT(nvarchar(4), YEAR_NUM) AS QUARTER_CAPTION,
       RIGHT(N'0' + CONVERT(nvarchar(2), MONTH_NUM), 2) + N'/' + CONVERT(nvarchar(4), YEAR_NUM) AS MONTH_CAPTION,
       (DATEDIFF(day, CONVERT(date, '19000101', 112), FL_DATE) % 7) + 1 AS WEEKDAY_NUM,
       CASE (DATEDIFF(day, CONVERT(date, '19000101', 112), FL_DATE) % 7) + 1
          WHEN 1 THEN N'Thứ Hai' WHEN 2 THEN N'Thứ Ba' WHEN 3 THEN N'Thứ Tư'
          WHEN 4 THEN N'Thứ Năm' WHEN 5 THEN N'Thứ Sáu' WHEN 6 THEN N'Thứ Bảy' ELSE N'Chủ Nhật' END AS WEEKDAY_NAME
FROM dbo.DIM_DATE
