SELECT TIME_ID, CRS_TIME, (CRS_TIME / 100) % 24 AS HOUR_NUM,
       RIGHT(N'0' + CONVERT(nvarchar(2), (CRS_TIME / 100) % 24), 2) + N':' +
       RIGHT(N'0' + CONVERT(nvarchar(2), CRS_TIME % 100), 2) AS TIME_CAPTION,
       RIGHT(N'0' + CONVERT(nvarchar(2), (CRS_TIME / 100) % 24), 2) + N':00' AS HOUR_CAPTION,
       CASE WHEN (CRS_TIME / 100) % 24 BETWEEN 6 AND 11 THEN 1
            WHEN (CRS_TIME / 100) % 24 BETWEEN 12 AND 13 THEN 2
            WHEN (CRS_TIME / 100) % 24 BETWEEN 14 AND 17 THEN 3 ELSE 4 END AS TIME_BAND_KEY,
       CONVERT(nvarchar(20), CASE WHEN (CRS_TIME / 100) % 24 BETWEEN 6 AND 11 THEN N'Sáng'
            WHEN (CRS_TIME / 100) % 24 BETWEEN 12 AND 13 THEN N'Trưa'
            WHEN (CRS_TIME / 100) % 24 BETWEEN 14 AND 17 THEN N'Chiều' ELSE N'Tối' END) AS TIME_BAND_NAME
FROM dbo.DIM_TIME
