-- 1. Tạo Database
CREATE DATABASE Flight_DW;
GO

USE Flight_DW;
GO

-- 2. Tạo các bảng Dimension
CREATE TABLE DIM_CARRIER (
    CARRIER_ID INT IDENTITY(1,1) PRIMARY KEY,
    CARRIER_CODE NVARCHAR(10) NOT NULL UNIQUE
);
GO

CREATE TABLE DIM_AIRPORT (
    AIRPORT_ID INT IDENTITY(1,1) PRIMARY KEY,
    AIRPORT_CODE NVARCHAR(10) NOT NULL UNIQUE,
    CITY_NAME NVARCHAR(100) NULL
);
GO

CREATE TABLE DIM_CANCELLATION (
    CANCELLATION_ID INT IDENTITY(1,1) PRIMARY KEY,
    CANCELLATION_CODE NVARCHAR(10) NOT NULL UNIQUE,
    CANCELLATION_REASON NVARCHAR(100) NULL
);
GO

CREATE TABLE DIM_DATE (
    DATE_ID INT IDENTITY(1,1) PRIMARY KEY,
    FL_DATE DATE NOT NULL UNIQUE,
    YEAR_NUM INT NULL,
    QUARTER_NUM INT NULL,
    MONTH_NUM INT NULL,
    DAY_NUM INT NULL
);
GO

-- 3. Tạo bảng Fact
CREATE TABLE FACT_FLIGHT (
    FLIGHT_ID INT IDENTITY(1,1) PRIMARY KEY,
    DATE_ID INT FOREIGN KEY REFERENCES DIM_DATE(DATE_ID),
    CARRIER_ID INT FOREIGN KEY REFERENCES DIM_CARRIER(CARRIER_ID),
    ORIGIN_AIRPORT_ID INT FOREIGN KEY REFERENCES DIM_AIRPORT(AIRPORT_ID),
    DEST_AIRPORT_ID INT FOREIGN KEY REFERENCES DIM_AIRPORT(AIRPORT_ID),
    CANCELLATION_ID INT FOREIGN KEY REFERENCES DIM_CANCELLATION(CANCELLATION_ID),
    CRS_DEP_TIME INT NULL,
    CRS_ARR_TIME INT NULL,
    DISTANCE FLOAT NULL,
    CANCELLED INT NULL,
    DEP_DELAY FLOAT NULL,
    ARR_DELAY FLOAT NULL,
    CARRIER_DELAY FLOAT NULL,
    WEATHER_DELAY FLOAT NULL,
    NAS_DELAY FLOAT NULL,
    SECURITY_DELAY FLOAT NULL,
    LATE_AIRCRAFT_DELAY FLOAT NULL
);
GO